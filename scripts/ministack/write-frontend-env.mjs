/**
 * Writes frontend/.env.development.local from the FrontEndEnvironment output of
 * the local stack, so `next dev` talks to the emulator rather than the deployed
 * dev environment. The same output is used for real deployments, which the
 * README reads with `aws cloudformation describe-stacks`.
 *
 * Only `next dev` loads the development file, so a production `next build`
 * can't pick up the emulator endpoints the way it would from .env.local.
 *
 * frontend/.env.development.local is overwritten, so keep any deployed dev
 * configuration you need somewhere else.
 *
 * Usage:
 *   pnpm ministack:up
 *   pnpm ministack:env
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const endpoint = process.env.MINISTACK_ENDPOINT ?? "http://localhost:20005";
const region = process.env.AWS_REGION ?? "ap-southeast-2";
const stackName = process.env.API_STACK_NAME ?? "local-transcription";
const timeoutSeconds = Number(process.env.MINISTACK_DEPLOY_TIMEOUT ?? 600);

const GENERATED_HEADER =
  "# Generated by pnpm ministack:env from the local stack outputs. Edits are lost on the next run.";

const envPath = resolve(
  import.meta.dirname,
  "../../frontend/.env.development.local",
);

/**
 * Driven through the AWS CLI to match the other MiniStack scripts, none of
 * which pull an SDK client into a workspace just to read the emulator.
 */
const aws = (args) => {
  try {
    return execFileSync(
      "aws",
      ["--endpoint-url", endpoint, "--region", region, ...args],
      {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "pipe"],
        env: {
          ...process.env,
          AWS_ACCESS_KEY_ID: "test",
          AWS_SECRET_ACCESS_KEY: "test",
        },
      },
    );
  } catch (error) {
    const stderr = error.stderr?.toString() ?? "";
    if (stderr.includes("does not exist")) return undefined;
    throw new Error(`aws ${args.join(" ")} failed: ${stderr || error.message}`);
  }
};

const readFrontEndEnvironment = () =>
  aws([
    "cloudformation",
    "describe-stacks",
    "--stack-name",
    stackName,
    "--query",
    "Stacks[0].Outputs[?OutputKey=='FrontEndEnvironment'].OutputValue",
    "--output",
    "text",
  ])?.trim();

const sleep = (ms) => new Promise((done) => setTimeout(done, ms));

/**
 * `pnpm ministack:up` waits on the bootstrap healthcheck, so the stack is
 * normally deployed by the time this runs. Poll anyway to cover a plain
 * `docker compose up -d`, which returns while cdklocal is still deploying.
 */
const waitForFrontEndEnvironment = async () => {
  const deadline = Date.now() + timeoutSeconds * 1000;
  let announced = false;
  while (true) {
    const value = readFrontEndEnvironment();
    if (value) return value;
    if (Date.now() > deadline) {
      throw new Error(
        `No FrontEndEnvironment output on ${stackName} after ${timeoutSeconds}s. Check pnpm ministack:logs.`,
      );
    }
    if (!announced) {
      console.log(`waiting for ${stackName} to finish deploying...`);
      announced = true;
    }
    await sleep(5000);
  }
};

const frontEndEnvironment = await waitForFrontEndEnvironment();

writeFileSync(envPath, `${GENERATED_HEADER}\n${frontEndEnvironment}\n`);

console.log(`wrote ${envPath} from ${stackName}`);
